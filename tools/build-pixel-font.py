# Columnas ocupadas por el glifo (el espacio mide 3).
def span(char):
    rows, desc, acc = G[char]
    lines = ([acc] if acc else []) + rows + desc
    cols = [i for line in lines for i, c in enumerate(line) if c == '#']
    if not cols:
        return 0, 3
    return min(cols), max(cols) + 1


def draw(rows, desc, acc, shift=0):
    pen = TTGlyphPen(None)
    lines = ([acc] if acc else []) + rows + desc
    top = 7 + (1 if acc else 0)
    for i, line in enumerate(lines):
        y = (top - 1 - i) * PX
        x = 0
        while x < len(line):
            if line[x] != '#':
                x += 1
                continue
            start = x
            while x < len(line) and line[x] == '#':
                x += 1
            # Un rectángulo por tramo horizontal (sentido horario: contorno exterior en TrueType).
            pen.moveTo(((start - shift) * PX, y))
            pen.lineTo(((start - shift) * PX, y + PX))
            pen.lineTo(((x - shift) * PX, y + PX))
            pen.lineTo(((x - shift) * PX, y))
            pen.closePath()
    return pen.glyph()


names = {char: f'uni{ord(char):04X}' for char in G}
order = ['.notdef'] + list(names.values())
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap({ord(char): name for char, name in names.items()})
glyphs = {'.notdef': draw(['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'], [], None)}
metrics = {'.notdef': (ADVANCE, 0)}
for char, name in names.items():
    first, last = span(char)
    glyphs[name] = draw(*G[char], shift=first)
    metrics[name] = ((last - first + 1) * PX, 0)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=900, descent=-200)
fb.setupOS2(sTypoAscender=900, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=900, usWinDescent=200, sxHeight=500, sCapHeight=700, fsType=0)
fb.setupNameTable({'familyName': 'Syndicate Pixel', 'styleName': 'Regular', 'uniqueFontIdentifier': 'SyndicatePixel-Regular', 'fullName': 'Syndicate Pixel', 'version': 'Version 1.000', 'psName': 'SyndicatePixel-Regular'})
fb.setupPost(isFixedPitch=0)
fb.setupHead(unitsPerEm=1000)
fb.font.flavor = 'woff'
out = Path(__file__).resolve().parent.parent / 'fonts' / 'syndicate-pixel.woff'
out.parent.mkdir(exist_ok=True)
fb.save(str(out))
print(f'{len(G)} glifos -> {out} ({out.stat().st_size} bytes)')

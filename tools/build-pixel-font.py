# Genera la fuente «Syndicate Pixel» (fonts/syndicate-pixel.woff) a partir de mapas de bits
# de 5 × 7 píxeles dibujados a mano: ASCII, letras del español (tildes, ñ, ü, ¿, ¡) y algunos
# signos («», ·, ×, …, €, º, ª). Proporcional: cada glifo ocupa su ancho real y 1 píxel de
# separación (así «10» no se lee «1 0»). 1 píxel = 100 unidades.
# Se ve nítida a 10, 20, 30… px. Los glifos que falten (emojis, flechas) caen en la fuente
# siguiente de la pila de CSS.
#   python tools/build-pixel-font.py      (requiere fontTools: pip install fonttools)

